function createSocialLink({ id, label, url, icon, viewBox }) {
    const link = document.createElement('a');
    link.href = url;
    link.id = id;
    link.className = 'icons-social-media';
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    link.setAttribute('aria-label', label);
    link.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="32" height="32" aria-hidden="true">${icon}</svg>`;
    return link;
}

export function initSocialButtons(containerSelector = '#contact-socials') {
    const container = document.querySelector(containerSelector);
    if (!container) return;

    container.replaceChildren();
    SOCIAL_LINKS.forEach((social) => {
        container.appendChild(createSocialLink(social));
    });
}
